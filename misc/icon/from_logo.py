#!/usr/bin/env python3
"""App icon from the project's logo image misc/icon/dw2_logo.png (provided by the project owner,
7.11.2026): writes misc/icon/dw2.ico (16..256, built into dw2.exe by host/dw2.rc) and
host/icon_rgba.h (64x64 RGBA, the window icon on Linux).

    python3 misc/icon/from_logo.py
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(HERE, "dw2_logo.png")
ICO = os.path.join(HERE, "dw2.ico")
HEADER = os.path.join(ROOT, "host", "icon_rgba.h")
SIZES = [16, 24, 32, 48, 64, 128, 256]


def badge():
    # the logo has its own transparency (rounded corners, glow): used as it is
    return Image.open(SRC).convert("RGBA")


def main():
    im = badge()
    imgs = [im.resize((s, s), Image.LANCZOS) for s in SIZES]
    imgs[-1].save(ICO, format="ICO", sizes=[(s, s) for s in SIZES], append_images=imgs[:-1])
    small = im.resize((64, 64), Image.LANCZOS)
    data = small.tobytes()
    with open(HEADER, "w") as f:
        f.write("/* Generated by misc/icon/from_logo.py from misc/icon/dw2_logo.png: 64x64 RGBA window icon. */\n")
        f.write("#define DW2_ICON_W 64\n#define DW2_ICON_H 64\n")
        f.write("static const unsigned char dw2_icon_rgba[64 * 64 * 4] = {\n")
        for i in range(0, len(data), 16):
            f.write("    " + ", ".join("0x%02x" % v for v in data[i:i + 16]) + ",\n")
        f.write("};\n")
    prev = Image.new("RGBA", (sum(SIZES) + 8 * len(SIZES), 256), (40, 40, 40, 255))
    x = 0
    for s, i in zip(SIZES, imgs):
        prev.alpha_composite(i, (x, 256 - s))
        x += s + 8
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    prev.save(os.path.join(ROOT, "build", "icon_preview.png"))


if __name__ == "__main__":
    main()
